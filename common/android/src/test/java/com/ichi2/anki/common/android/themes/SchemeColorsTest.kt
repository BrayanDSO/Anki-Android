package com.ichi2.anki.common.android.themes

import android.annotation.SuppressLint
import android.content.Context
import androidx.core.content.ContextCompat
import androidx.test.core.app.ApplicationProvider
import com.google.android.material.color.utilities.DynamicColor
import com.google.android.material.color.utilities.Hct
import com.google.android.material.color.utilities.MaterialDynamicColors
import com.google.android.material.color.utilities.SchemeContent
import com.ichi2.anki.common.android.R
import org.junit.Test
import org.junit.runner.RunWith
import org.robolectric.RobolectricTestRunner
import kotlin.test.fail

/**
 * The `scheme_*` colors in `theme_scheme_colors.xml` are Material 3 color schemes generated from
 * a seed color, with the algorithm Material uses for content-based dynamic colors
 * ([com.google.android.material.color.DynamicColorsOptions.Builder.setContentBasedSource]).
 *
 * To change a seed, or after a Material upgrade changes the algorithm, replace the colors with
 * the XML printed by the failure.
 */
@RunWith(RobolectricTestRunner::class)
@SuppressLint("RestrictedApi")
class SchemeColorsTest {
    private val context: Context get() = ApplicationProvider.getApplicationContext()

    @Test
    fun `scheme colors are generated from their seed`() {
        val mismatches =
            schemes.flatMap { scheme ->
                scheme.colors().mapNotNull { (name, expected) ->
                    val actual = runCatching { ContextCompat.getColor(context, colorRes(name)) }.getOrNull()
                    if (actual == expected) null else "$name: expected ${expected.hex()}, was ${actual?.hex()}"
                }
            }
        if (mismatches.isNotEmpty()) {
            fail(mismatches.joinToString("\n") + "\n\nExpected theme_scheme_colors.xml:\n" + generateXml())
        }
    }

    private class Scheme(
        val name: String,
        val seed: Int,
        val isDark: Boolean,
    ) {
        fun colors(): List<Pair<String, Int>> {
            val scheme = SchemeContent(Hct.fromInt(seed), isDark, 0.0)
            val colors = MaterialDynamicColors()
            return roles.map { (role, color) -> "scheme_${name}_$role" to color(colors).getArgb(scheme) }
        }
    }

    private fun generateXml() =
        buildString {
            appendLine("""<?xml version="1.0" encoding="utf-8"?>""")
            appendLine("<!-- SPDX-License-Identifier: GPL-3.0-or-later -->")
            appendLine("<!-- Generated by SchemeColorsTest: do not edit by hand -->")
            appendLine("""<resources xmlns:tools="http://schemas.android.com/tools" tools:ignore="UnusedResources">""")
            for (scheme in schemes) {
                appendLine()
                val mode = if (scheme.isDark) "dark" else "light"
                appendLine("    <!-- ${scheme.name}: seed ${scheme.seed.hex()}, $mode -->")
                for ((name, color) in scheme.colors()) {
                    appendLine("""    <color name="$name">${color.hex()}</color>""")
                }
            }
            append("</resources>")
        }

    private fun colorRes(name: String) = R.color::class.java.getField(name).getInt(null)

    private fun Int.hex() = "#%08X".format(this)

    companion object {
        private const val BRAND_SEED = 0xFF03A9F4.toInt()
        private const val PLAIN_SEED = 0xFF9E9E9E.toInt()

        private val schemes =
            listOf(
                Scheme("light", BRAND_SEED, isDark = false),
                Scheme("dark", BRAND_SEED, isDark = true),
                Scheme("plain", PLAIN_SEED, isDark = false),
            )

        /** Material 3 color roles, by their resource suffix */
        private val roles: List<Pair<String, (MaterialDynamicColors) -> DynamicColor>> =
            listOf(
                "primary" to { it.primary() },
                "on_primary" to { it.onPrimary() },
                "primary_container" to { it.primaryContainer() },
                "on_primary_container" to { it.onPrimaryContainer() },
                "inverse_primary" to { it.inversePrimary() },
                "primary_fixed" to { it.primaryFixed() },
                "primary_fixed_dim" to { it.primaryFixedDim() },
                "on_primary_fixed" to { it.onPrimaryFixed() },
                "on_primary_fixed_variant" to { it.onPrimaryFixedVariant() },
                "secondary" to { it.secondary() },
                "on_secondary" to { it.onSecondary() },
                "secondary_container" to { it.secondaryContainer() },
                "on_secondary_container" to { it.onSecondaryContainer() },
                "secondary_fixed" to { it.secondaryFixed() },
                "secondary_fixed_dim" to { it.secondaryFixedDim() },
                "on_secondary_fixed" to { it.onSecondaryFixed() },
                "on_secondary_fixed_variant" to { it.onSecondaryFixedVariant() },
                "tertiary" to { it.tertiary() },
                "on_tertiary" to { it.onTertiary() },
                "tertiary_container" to { it.tertiaryContainer() },
                "on_tertiary_container" to { it.onTertiaryContainer() },
                "tertiary_fixed" to { it.tertiaryFixed() },
                "tertiary_fixed_dim" to { it.tertiaryFixedDim() },
                "on_tertiary_fixed" to { it.onTertiaryFixed() },
                "on_tertiary_fixed_variant" to { it.onTertiaryFixedVariant() },
                "error" to { it.error() },
                "on_error" to { it.onError() },
                "error_container" to { it.errorContainer() },
                "on_error_container" to { it.onErrorContainer() },
                "background" to { it.background() },
                "on_background" to { it.onBackground() },
                "surface" to { it.surface() },
                "on_surface" to { it.onSurface() },
                "surface_variant" to { it.surfaceVariant() },
                "on_surface_variant" to { it.onSurfaceVariant() },
                "inverse_surface" to { it.inverseSurface() },
                "inverse_on_surface" to { it.inverseOnSurface() },
                "surface_dim" to { it.surfaceDim() },
                "surface_bright" to { it.surfaceBright() },
                "surface_container_lowest" to { it.surfaceContainerLowest() },
                "surface_container_low" to { it.surfaceContainerLow() },
                "surface_container" to { it.surfaceContainer() },
                "surface_container_high" to { it.surfaceContainerHigh() },
                "surface_container_highest" to { it.surfaceContainerHighest() },
                "outline" to { it.outline() },
                "outline_variant" to { it.outlineVariant() },
            )
    }
}
